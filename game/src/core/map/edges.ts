import { neighbor, type Direction, type Hex } from '../hex/index.js';

/**
 * Признаки ребра — того, что находится МЕЖДУ двумя клетками.
 * Битовая маска: занято 4 бита из 8, запас на четыре типа без смены формата.
 *
 * Река здесь больше не хранится (шаг 9c): бит 0 раньше значил «река», из-за чего
 * река была границей между клетками, а не водой в клетке, и не подчинялась ни
 * одному правилу воды (тепло, глубина, укрытие). Теперь река — обычная
 * `TerrainType.Water`, а слот старого бита 0 остаётся свободным.
 */
export const EDGE_NONE = 0;
/** Обрыв: шагом непроходимо в обе стороны независимо от перепада высот. */
export const EDGE_CLIFF = 1 << 1;
/** Стена: непроходима, перекрывает видимость до своей высоты, разрушаема. */
export const EDGE_WALL = 1 << 2;
/** Ворота: как стена, но открываются или выбиваются. */
export const EDGE_GATE = 1 << 3;
/** Мост: отменяет обрыв и глубину воды на этом ребре, переход стоит 1 MP. */
export const EDGE_BRIDGE = 1 << 4;

export const EDGE_FLAG_NAMES: ReadonlyMap<number, string> = new Map([
  [EDGE_CLIFF, 'cliff'],
  [EDGE_WALL, 'wall'],
  [EDGE_GATE, 'gate'],
  [EDGE_BRIDGE, 'bridge'],
]);

/**
 * Каноническое имя ребра: пара (клетка, направление 0..2).
 *
 * Ребро принадлежит двум клеткам сразу. Если хранить по шесть рёбер на клетку,
 * каждое записано дважды и рано или поздно рассинхронизируется. Поэтому хранятся
 * только направления NW, NE, E (индексы 0..2), а SE, SW, W читаются у соседа как
 * его NW, NE, E — это ровно `opposite()` от них.
 */
export function canonicalEdge(h: Hex, dir: Direction): { hex: Hex; slot: 0 | 1 | 2 } {
  if (dir < 3) return { hex: h, slot: dir as 0 | 1 | 2 };
  return { hex: neighbor(h, dir), slot: (dir - 3) as 0 | 1 | 2 };
}
