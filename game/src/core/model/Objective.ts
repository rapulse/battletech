/**
 * Задача боя (шаг 19b).
 *
 * **Единственное место, где Часть 2 меняет боевое ядро** (ловушка 1 брифинга
 * шага 19). До этого шага условие победы было константой: сторона побеждает,
 * когда у другой не осталось машин в строю. Пять типов миссий шага 16
 * (`data/contracts.json`) различались только силой противника, оплатой, сроком
 * и долей трофеев — то есть ничем внутри самого боя.
 *
 * Задача приходит **параметром `BattleState`**, а не ветками по типу миссии в
 * правилах. Причина прямая: правило «кто победил» обязано остаться ОДНИМ и для
 * полного боя, и для быстрого расчёта (`bridge/fastResolve.ts`), иначе две
 * точности начнут присуждать победу по разным правилам — а на сравнении долей
 * побед стоит вся калибровка шага 18.
 *
 * **Ядро боя не знает слова «контракт».** Здесь нет ни `garrison`, ни `raid`:
 * какой миссии какая задача соответствует, решает кампания
 * (`data/contracts.json` → `missions[].objective`). Бой знает только «продержись
 * столько-то ходов» и «выведи столько-то машин».
 *
 * ## Что здесь есть и чего сознательно нет
 *
 * Три вида задач, и все три считаются по тому, что в бою УЖЕ есть, — по
 * машинам и по номеру хода. Ни объектов на карте, ни небоевых юнитов, ни зон
 * эвакуации этот шаг не заводит (решение пользователя 2026-09-03: «сейчас
 * добавить что легко, потом можно вводить больше типов миссий с объектами на
 * карте»). Что для этого понадобится — записано в
 * `wiki/design/campaign/global-layer.md`, раздел «Задачи боя».
 */

import type { Side } from './MechUnit.js';

export type BattleObjective =
  | {
      /**
       * Вывести противника из строя целиком — правило Части 1 и умолчание
       * всякого боя вне кампании.
       */
      readonly kind: 'destroy';
    }
  | {
      /**
       * Продержаться на поле заданное число ходов.
       *
       * Оборона: победа не в том, чтобы всех перебить, а в том, чтобы не дать
       * себя выбить до срока. Досрочная победа тоже засчитывается — противник,
       * выбитый на пятом ходу, не станет атаковать на десятом.
       */
      readonly kind: 'hold';
      readonly rounds: number;
    }
  | {
      /**
       * Вывести из строя ДОЛЮ противника — и на этом бой окончен.
       *
       * Рейд и разведка: задача не уничтожить гарнизон, а нанести урон и уйти.
       * Доля считается от числа машин противника в этом бою и округляется
       * вверх: половина от трёх — это две машины, а не полторы.
       *
       * **Бой по контракту задаёт число прямо (`quota`).** Условие, которое игрок
       * прочёл в контракте («вывести 1 из 2 машин»), не должно расти от того, что
       * разведка ошиблась и на поле вышло три: считается от ОБЪЯВЛЕННОГО состава и
       * записывается сюда при сборке брифинга (`contractBrief`). Без него — доля от
       * состава на поле, как в боях вне кампании.
       */
      readonly kind: 'cripple';
      readonly share: number;
      readonly quota?: number;
    }
  | {
      /**
       * Разрушить объекты-цели противника (шаг 73d, штурм укреплённого мира).
       *
       * Победа — когда разрушены все объекты противника; добивать его машины
       * не обязательно (решение пользователя 2026-09-24). Выбить всех — тоже
       * победа, как при любой задаче.
       */
      readonly kind: 'destroyTargets';
    }
  | {
      /**
       * Удержать свои объекты-цели (шаг 73d, оборона ключевой системы).
       *
       * Продержаться `rounds` ходов, пока цел хоть один объект роты. Разрушены
       * все — поражение досрочно, даже если рота цела.
       */
      readonly kind: 'protectTargets';
      readonly rounds: number;
    };

/** Задача по умолчанию: правило Части 1. Любой бой вне кампании идёт с ней. */
export const DESTROY_ALL: BattleObjective = { kind: 'destroy' };

/** Задача по умолчанию — ту, что была всегда. Отдельная функция ради читаемости условий. */
export function isDefaultObjective(objective: BattleObjective): boolean {
  return objective.kind === 'destroy';
}

/**
 * Что бою нужно знать о положении дел, чтобы присудить исход.
 *
 * Числа, а не машины: считать их умеют оба расчёта — и полный бой по
 * `BattleState`, и быстрый по своему списку юнитов, — а правило исхода одно на
 * двоих (`rules/objective.ts`).
 */
export interface ObjectiveProgress {
  /**
   * Сколько ходов ЗАВЕРШЕНО (в быстром расчёте — условных раундов).
   *
   * Именно завершено, а не «идёт»: оборона на три хода выполняется в конце
   * третьего. Полный бой считает `state.turn − 1`, быстрый расчёт — свой
   * счётчик раундов.
   */
  readonly roundsCompleted: number;
  readonly playerActive: number;
  readonly opforActive: number;
  /** Сколько машин противника вышло в бой всего — знаменатель доли для `cripple`. */
  readonly opforTotal: number;
  /** Целых объектов-целей у роты и у противника (шаг 73d). */
  readonly playerTargets: number;
  readonly opforTargets: number;
  /** Сколько объектов-целей стояло на поле у противника и у роты с начала боя. */
  readonly playerTargetsTotal: number;
  readonly opforTargetsTotal: number;
}

/** Кто победил, или `null` — бой ещё не кончен. */
export type ObjectiveVerdict = Side | 'draw' | null;
