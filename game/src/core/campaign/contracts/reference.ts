import { Rng } from '../../rng/index.js';
import { generateAssembly } from '../../rules/construction.js';
import { makeRecord } from '../mech/MechRecord.js';
import { mechValue } from '../market/pricing.js';

/**
 * Единица, в которой меряется оплата контракта (шаг 16).
 *
 * **Оплата выставляется относительно `mechValue`, а не наоборот** — это вывод
 * шагов 13 и 15, записанный во входе брифинга шага 16. Плоская заглушка в
 * 70 000 C-Bills оказалась негодной ровно потому, что была абсолютным числом:
 * исправная средняя машина оценивается больше чем в миллион, и одна проданная
 * трофейная машина стоила семи контрактов. Значит, единицей должна быть машина,
 * а не C-Bill.
 *
 * Эталон — **та самая серийная 55-тонная машина, с которой рота начинает**
 * (`sim/campaign/batch.ts::STARTER_CHASSIS`), собранная фиксированным сидом.
 * Не «средняя по каталогу» и не «медианная по тоннажу»: средняя величина
 * поехала бы вместе с пополнением каталога шасси, а стартовая машина — это то,
 * с чем игрок сравнивает всё остальное, и она не меняется от того, что в
 * каталоге прибавилось десять новых корпусов.
 *
 * Считается один раз при загрузке модуля и НЕ входит ни в состояние, ни в
 * сохранение: это свойство данных, а не кампании.
 */

/** Шасси эталона. Оно же — стартовое шасси роты. */
export const REFERENCE_CHASSIS = 'IS-H55-R3F2';

/** Сид сборки эталона. Любое фиксированное число; важно только, что оно не меняется. */
const REFERENCE_SEED = 20260902;

/**
 * Цена эталонной машины в C-Bills.
 *
 * Класс исполнения — серийный (умолчание `generateAssembly`, предохранитель
 * из решения 8 §7 пайплайна), состояние — паспортное: эталон не бывает побитым.
 */
export const REFERENCE_MECH_VALUE: number = mechValue(
  makeRecord({
    id: 'reference',
    assembly: generateAssembly({ chassisCode: REFERENCE_CHASSIS, role: 'brawler' }, new Rng(REFERENCE_SEED)),
  }),
);
