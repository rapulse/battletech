import type { SystemProfile } from '../galaxy/profile.js';
import { prosperityOf, type WarState } from '../war/index.js';
import type { OutfitSpec } from '../mech/outfit.js';
import { factionKind } from './relations.js';
import { CONTRACTS, type OpforType } from './schema.js';

/**
 * Снабжение части (шаг 21a, часть C) — то, чем экономика фракции выходит в бой.
 *
 * Обещание `wiki/design/campaign/global-layer.md`: «богатая фракция снаряжает
 * лучше, разорённая — хуже; линия фронта и доходы планет начинают влиять на то,
 * что игрок видит на поле, а не только на цифры в отчёте». До этого шага класс
 * части определяли только ВИД ВЛАДЕЛЬЦА и СИЛА ГАРНИЗОНА, поэтому разорённый
 * Ляо выставлял ровно то же, что богатый Дэвион.
 *
 * **Ручка ровно одна — `supply.link`** (решение 3, `wiki/decisions.md`). Она
 * множит ПОПРАВКУ, а не результат, поэтому `link = 0` возвращает поведение до
 * 21a точно. Подтянуть сложность после ручной игры — правка одного числа в
 * `data/contracts.json` и повторный замер, а не правка кода.
 *
 * **Центр поправки — `supply.mid` = 1.0, середина ПО СФЕРЕ, и это осознанно не
 * среднее по бирже.** Соблазн был прямой: биржа на сиде 1 даёт среднее
 * снабжение 1.06 (84 % предложений идут против пиратов, и биржа взвешена по
 * работе, а не по мирам), и центр 1.06 обнулил бы сдвиг ровно на этом сиде. Но
 * на сиде 4242 та же биржа даёт 0.80: пираты держат 23 мира, и их достаток на
 * мир гуляет от сида к сиду сильнее, чем у любого Дома. Центр, подогнанный под
 * один сид, на другом промахивается сильнее, чем неподогнанный. Вдобавок состав
 * биржи целиком переписывает 21b — «84 % против пиратов» ровно та цифра, ради
 * которой он делается. Поэтому центр взят там, где он не зависит ни от сида, ни
 * от состава биржи: достаток нормирован к единице по мирам Сферы.
 */

const S = CONTRACTS.opfor.supply;

function clamp(v: number, lo: number, hi: number): number {
  return v < lo ? lo : v > hi ? hi : v;
}

/**
 * Насколько хорошо снабжена часть этой фракции на этом мире. 1.0 — середина.
 *
 * Три слагаемых, и каждое отвечает своему решению:
 *
 * 1. **Достаток фракции на мир** (`war/economy.ts`) — решение 1. Не абсолютная
 *    казна: 396 миров Дэвиона против 134 у Ляо дали бы вечную кастовость.
 * 2. **Военная промышленность системы** — своя арсенальная база снаряжает свой
 *    гарнизон. Это то самое место, где заводы работают: в доход фракции они
 *    почти не идут (`data/war.json`, `perMilitary`), потому что военпром растёт
 *    от близости к чужой границе, а не от богатства.
 * 3. **Разорение** — второй раз после дохода. Разорённый мир и приносит меньше,
 *    и снаряжает свой гарнизон хуже.
 *
 * Центр по военпрому — ЗАМЕРЕННОЕ среднее по двум тысячам миров (3.66), а не
 * середина шкалы 0..10: шкала заполнена неравномерно, и центр, взятый на глаз,
 * тихо сдвинул бы всю биржу в одну сторону.
 */
export function supplyLevel(
  war: WarState,
  factionId: string,
  profile: SystemProfile,
  ruined = 0,
): number {
  const local = 1 + S.militaryWeight * ((profile.industryMilitary - S.militaryMid) / 10);
  const value = prosperityOf(war, factionId) * local * (1 - S.ruinWeight * clamp(ruined, 0, 1));
  return Math.round(clamp(value, S.min, S.max) * 1000) / 1000;
}

/**
 * Тип отряда противника — таблица «Снаряжение отрядов» из `global-layer.md`
 * плюс поправка на снабжение.
 *
 * **Лестница militia → line → guard есть только у тех, у кого она есть.**
 * Клан выходит клановой Звездой при любой казне; у пиратов, периферии и
 * независимых миров линейных полков и гвардии нет вовсе, сколько бы они ни
 * награбили. Экономика двигает часть по лестнице, а не выдаёт лестницу тому,
 * у кого её нет, — иначе разбогатевшая пиратская вольница выставляла бы
 * гвардейский полк.
 *
 * Разорение при этом умеет опустить и Дом до ополчения: это и есть обещание
 * плана — «разорённая фракция выставляет ополчение на восстановленном хламе».
 * При среднем снабжении в эту ступень не попасть (`militiaBelow` = 0, а
 * гарнизон не бывает отрицательным), и ровно так связь и центрирована.
 */
export function opforTypeOf(target: string, garrison: number, supply = 1): OpforType {
  const kind = factionKind(target);
  if (kind === 'clan') return 'clan';
  if (kind === 'pirates' || kind === 'periphery' || kind === 'independent') return 'militia';

  const effective = garrison + S.link * S.guardShift * (supply - S.mid);
  if (effective < S.militiaBelow) return 'militia';
  return effective >= CONTRACTS.opfor.guardFrom ? 'guard' : 'line';
}

/**
 * Комплектность части с поправкой на снабжение.
 *
 * Вторая ось, и без неё половина шага не работает: одним порогом типа
 * разорённый Ляо и богатый Дэвион остались бы с побайтово одинаковой «линией».
 * Одной комплектностью тоже нельзя — тип виден игроку ДО боя, а класс
 * исполнения только после разведки (решение 4 §7 пайплайна), и половина отдачи
 * оказалась бы не видна без `Survey`.
 *
 * Верх брони упирается в паспорт: «лучше полного комплекта» не бывает, богатство
 * даёт полный, а не сверхполный.
 */
export function supplyOutfit(base: OutfitSpec, supply: number): OutfitSpec {
  const shift = S.link * (supply - S.mid);
  const armor = S.armorShift * shift;
  const [lo, hi] = base.armorShare;
  const [missLo, missHi] = base.missingItems;
  const missing = S.missingShift * shift;
  return {
    armorShare: [clamp(lo + armor, 0.1, 1), clamp(hi + armor, 0.1, 1)],
    missingItems: [Math.max(0, Math.round(missLo - missing)), Math.max(0, Math.round(missHi - missing))],
  };
}

/**
 * Число машин против их качества.
 *
 * Отдельная ось, а не вторая ручка сложности. Плотная промышленная фракция
 * выставляет МЕНЬШЕ машин, но гвардейских; редкая дотационная — БОЛЬШЕ, но
 * плохих. Сто слабых миров дают не силу, а распыление: людей и заводов на них
 * мало, зато держать надо все. Ровно поэтому достаток и меряется на мир
 * (решение 1), а размер уходит сюда: иначе «больше планет» значило бы «сильнее»
 * и развивать миры было бы незачем.
 *
 * Заодно эта ось чинит то, что нашёл замер шага. Без неё разброс силы
 * противника был чистым подарком тому, кто выбирает контракты: бот брал
 * заведомо слабых, и кампания выходила на треть безопаснее при ЛЮБОЙ
 * калибровке центра — сдвигать `mid` было бесполезно, потому что дело было не в
 * среднем, а в возможности выбирать. Когда слабый противник берёт числом,
 * бесплатного выбора не остаётся, и произведение «количество × угроза»
 * держится само.
 */
export function supplyCount(supply: number): number {
  return Math.max(0.25, 1 + S.link * S.countShift * (S.mid - supply));
}

/**
 * Поправка к ЧИТАЕМОЙ ДО БОЯ оценке сил.
 *
 * Не балансная ручка, а условие честности, записанное в самом `threat.ts`: «у
 * контракта должна быть оценка силы, сопоставимая с силой отряда» и «разойдись
 * они, и сложность, читаемая до боя, перестала бы совпадать с боем».
 *
 * Снабжение меняет то, что реально выйдет на поле, — значит обязано менять и
 * то, что игрок с ботом видят заранее. Без этой поправки замер показывал
 * смягчение кампании во ВСЕХ конфигурациях рычагов, и не от их калибровки:
 * разброс силы противника вырос, оценка осталась средней, и бот систематически
 * ошибался в свою пользу — брал работу, которая оказывалась легче обещанного,
 * и отказывался от той, что была легче тоже.
 */
export function supplyThreat(supply: number): number {
  return 1 + S.link * S.threatShift * (supply - S.mid);
}
