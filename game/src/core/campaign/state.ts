export const CAMPAIGN_RULES_VERSION = 25;

/**
 * Режим кампании (шаг 74), выбирается при основании отряда и не меняется.
 *
 * `standard` — канонические правила наёмника. `sandbox` — свободная игра:
 * беспроцентные кредиты по требованию и высадка без удержания гонорара.
 * Бот замера, соперники и мир песочницу не видят: замеры баланса всегда идут
 * по стандарту.
 */
export type CampaignMode = 'standard' | 'sandbox';

export interface CampaignInit {
  readonly companyName?: string;
  /** Режим кампании (шаг 74). По умолчанию `standard`. */
  readonly mode?: CampaignMode;
  /** День начала. По умолчанию 0 — 1 января 3053 года (`clock.ts::EPOCH`). */
  readonly startDay?: number;
  readonly company?: CompanyInit;
  /**
   * Сид мира. По умолчанию равен сиду кампании; отдельным полем — чтобы две
   * кампании можно было играть в одной и той же галактике, а одну и ту же
   * кампанию — в разных.
   */
  readonly worldSeed?: number;
  /** Где рота начинает. По умолчанию — биржа наёмников из `data/galaxy/galaxy.json`. */
  readonly systemId?: string;
}

/**
 * Состояние кампании — второе ядро проекта, устроенное так же, как боевое
 * (`core/model/BattleState.ts`): изменяемый контейнер, неизменяемые значения
 * внутри, единственный способ его менять — команда (`commands/execute.ts`).
 *
 * На шаге 10 здесь только время, имя роты и ГПСЧ. Отряд, галактика, деньги и
 * контракты приходят шагами 11–16 и встают полями рядом — форма состояния для
 * этого и заведена заранее.
 */
export class CampaignState {
  /** Мастер-сид кампании. Из него выводятся все потоки. */
  readonly seed: number;
  readonly rng: CampaignRngSet;
  readonly rulesVersion: number = CAMPAIGN_RULES_VERSION;

  day: number;
  companyName: string;
  /** Режим кампании (шаг 74): задаётся при основании и дальше не меняется. */
  readonly mode: CampaignMode;

  /** Очередь отложенных задач. Всегда отсортирована по `(day, seq)`. */
  queue: readonly ScheduledEvent[] = [];

  /**
   * Монотонный счётчик постановок в очередь.
   *
   * Часть состояния, а не локальная переменная: он входит в снимок и в хэш,
   * иначе загруженная кампания начнёт нумеровать задачи заново и порядок
   * исполнения на равных днях разойдётся с исходным.
   */
  nextSeq = 0;

  /** Рота: машины, пилоты, склад, деньги (шаг 13, `company/types.ts`). Меняется только командами. */
  company: Company;

  /**
   * Сид мира: из него выводится профиль каждой системы (`galaxy/profile.ts`).
   * Каталог систем одинаков всегда, а вот население, промышленность и климат —
   * свойство конкретного мира, и они не хранятся нигде, только выводятся.
   */
  readonly worldSeed: number;

  /** Где рота стоит. В пути — система, из которой ушла последняя пройденная нога. */
  systemId: string;

  /** Маршрут, пока рота в пути. `null` на стоянке. */
  travel: TravelState | null;

  /**
   * НАЙМ (переработан 2026-09-10). Два поля, и оба обязаны быть в состоянии.
   *
   * `hireReadyDay` — с какого дня доступна попытка поиска. Попытки НЕ копятся:
   * это один день в будущем, а не счётчик. Пропустил три декады — попытка всё
   * равно одна (решение пользователя).
   *
   * `recruit` — кандидат, которого показали и по которому ещё не решили. Лежит
   * в состоянии ЦЕЛИКОМ, а не выводится из сида: он уже вытянут, деньги за
   * поиск уже уплачены, и перезагрузка страницы не должна ни отменять расход,
   * ни давать переиграть бросок другим кандидатом.
   */
  hireReadyDay: number;
  recruit: Pilot | null;

  /**
   * Достижения роты (шаг 69): что открыто и в какой день, плюс счёт добиваний.
   * Лежат в состоянии, а не в профиле браузера — уезжают вместе с файлом
   * сохранения и не теряются с очисткой данных сайта. Меняются только командами
   * (`achievements/index.ts`).
   */
  achievements: AchievementsState = EMPTY_ACHIEVEMENTS;

  /**
   * Взятый контракт (шаг 16). `null` — рота свободна.
   *
   * Один за раз, и это правило, а не упрощение: наёмный отряд подписывается под
   * срок и штраф, и второй контракт на те же сутки означал бы, что срок ничего
   * не стоит. Несколько контрактов сразу — это несколько боевых групп, а они
   * начинаются вместе со вторым десантным кораблём (решение 10 §7, M11+).
   */
  contract: ActiveContract | null;

  /**
   * Чем мир отличается от каталога: смена владельца, разведка, разорение,
   * покупки. Разрежённая карта — единственное, что растёт с игрой
   * (`galaxy/delta.ts`).
   */
  deltas: GalaxyDeltas;

  /**
   * Репутация отряда (шаг 20): отношение у каждой фракции, известность,
   * надёжность и матрица отношений фракций между собой.
   *
   * Здесь, а не в дельтах мира, и это не мелочь: дельта — про МЕСТО («этой
   * системой теперь владеет Курита»), а репутация — про РОТУ («Курита теперь
   * знает, кто вы»). Она едет с отрядом через всю Сферу и не принадлежит ни
   * одной системе.
   */
  reputation: ReputationState;

  /**
   * Экономика фракций (шаг 21a) и фронт (шаг 21b): казна, доход, содержание и
   * военный фонд по направлениям.
   *
   * Здесь, а не в дельтах мира, по той же причине, по которой репутация не в
   * дельтах: дельта — про МЕСТО («этой системой теперь владеет Курита»), а
   * экономика — про АКТОРА («у Куриты стало на один мир больше и на столько-то
   * больше дохода»). Она не принадлежит ни одной системе и меняется от каждой.
   *
   * Начальные суммы выводятся из карты один раз, в конструкторе: профиль
   * системы не хранится нигде, и складывать две тысячи профилей на каждом такте
   * нельзя. Дальше суммы правятся приращением.
   */
  war: WarState;

  /**
   * Отряды-соперники (шаг 22): те же роты, что у игрока, со своим местом,
   * репутацией и историей.
   *
   * В состоянии, а не выводятся (решение 1 шага 22), и по той же причине, что
   * репутация: у соперника есть ИСТОРИЯ — парк, потери, отношения у
   * нанимателей, место в таблице, — а история не выводится из сида. Список
   * ПЛОТНЫЙ, в отличие от дельт и репутации: соперников восемь, а не две
   * тысячи, и «отличается от начального» для них не определено — отряд,
   * потерявший машину, отличается от начального с первого же боя.
   *
   * Порождаются в конструкторе тем же приёмом, что стартовая рота: сид мира на
   * входе, список отрядов на выходе (`rivals/founding.ts`).
   */
  rivals: RivalsState;

  /**
   * Гарнизоны миров из машин роты (шаг 86b, `company/garrison.ts`): где стоит каждая машина вне корабля и
   * политика мира. Записи машин остаются в `company.mechs` — здесь только их место.
   */
  garrison: GarrisonState = NO_GARRISON;

  /**
   * Управление державой роты (шаг 88, `realm/sectors.ts`): секторы с губернаторами, резерв кассы, закреплённые
   * миры и стойки фронтов. Политики губернаторов и стоек отдают по нему те же команды, что игрок.
   */
  realm: RealmState = NO_REALM;

  constructor(seed: number, init: CampaignInit = {}) {
    this.seed = seed >>> 0;
    this.rng = new CampaignRngSet(this.seed);
    this.day = init.startDay ?? 0;
    this.companyName = init.companyName ?? NAMES.defaults.companyName;
    this.mode = init.mode ?? 'standard';
    this.company = makeCompany(init.company);
    this.worldSeed = (init.worldSeed ?? this.seed) >>> 0;
    this.systemId = init.systemId ?? START_SYSTEM_ID;
    if (!GALAXY.has(this.systemId)) {
      throw new RangeError(`Кампания начинается в несуществующей системе: ${this.systemId}`);
    }
    this.travel = null;
    // Попытка найма доступна с первого дня: рота начинает с трёх пилотов, и
    // ждать две недели, чтобы просто посмотреть на биржу, было бы наказанием
    // ни за что.
    this.hireReadyDay = this.day;
    this.recruit = null;
    this.contract = null;
    this.deltas = NO_DELTAS;
    this.reputation = makeReputation();
    this.war = makeWarState(this.worldSeed, this.deltas);
    // Соперники заводятся вокруг той системы, в которой рота начинает: они —
    // МЕСТНАЯ конкуренция, а не перепись всех наёмников Сферы (`rivals/founding.ts`).
    this.rivals = foundRivals(this.worldSeed, this.systemId);

    // Первая зарплата ставится здесь, а не командой: содержание идёт с самого
    // первого дня кампании (десантный корабль стоит денег и с пустым ангаром),
    // и `execute()` остаётся точкой ТОЛЬКО изменения уже существующего
    // состояния, а не его инициализации. `restore()` (`save.ts`) поднимает
    // очередь из снимка следующей строкой и эту затирает — событие в свежей
    // кампании ставится ровно один раз.
    this.queue = insertScheduled(this.queue, {
      day: this.day + ECONOMY.payroll.intervalDays,
      seq: this.nextSeq,
      task: { kind: 'payroll' },
    });
    this.nextSeq += 1;

    // Затухание репутации — такая же самоподдерживающаяся задача очереди, как
    // содержание: она сама переставляет себя на следующий месяц. Ставится
    // здесь по той же причине, что и первая зарплата, и так же затирается
    // `restore()` при загрузке снимка.
    this.queue = insertScheduled(this.queue, {
      day: this.day + REPUTATION.decay.intervalDays,
      seq: this.nextSeq,
      task: { kind: 'decayTick' },
    });
    this.nextSeq += 1;

    // Отдых роты: раз в декаду у каждого пилота в строю заживает одна травма
    // (`company/medbay.ts::restPilot`). Четвёртая самопереставляющаяся задача
    // рядом с содержанием и затуханием и, как они, затирается `restore()`.
    this.queue = insertScheduled(this.queue, {
      day: this.day + REST_DAYS,
      seq: this.nextSeq,
      task: { kind: 'restTick' },
    });
    this.nextSeq += 1;

    // Такт экономики фракций (шаг 21a) — третья самопереставляющаяся задача
    // рядом с содержанием и затуханием. День первого такта выровнен по границе
    // ДЕКАДЫ, а не отсчитан от дня основания: биржа с 21a читает экономику, а
    // предложения в системе неизменны внутри декады (`contracts/board.ts`).
    // Такт, сдвинутый на середину декады, менял бы состав биржи при неизменном
    // её сиде — это читалось бы как поломка генератора, а не как ход мира.
    this.queue = insertScheduled(this.queue, {
      day: nextEconomyTickDay(this.day),
      seq: this.nextSeq,
      task: { kind: 'economyTick' },
    });
    this.nextSeq += 1;

    // Такт фронта (шаг 21b) — на ТОТ ЖЕ день, что и такт экономики, и строго
    // после него: фракции сперва копят, потом воюют накопленным. Порядок держит
    // номер постановки (`compareScheduled` разводит равные дни по `seq`), а не
    // совпадение — поэтому обе задачи и ставятся здесь подряд.
    this.queue = insertScheduled(this.queue, {
      day: nextEconomyTickDay(this.day),
      seq: this.nextSeq,
      task: { kind: 'frontTick' },
    });
    this.nextSeq += 1;

    // Такт событий мира (шаг 84) — на ТОТ ЖЕ день и сразу после фронта: событие читает карту и
    // отношения, какими их оставила декада.
    this.queue = insertScheduled(this.queue, {
      day: nextEconomyTickDay(this.day),
      seq: this.nextSeq,
      task: { kind: 'eventTick' },
    });
    this.nextSeq += 1;

    // Такт развития планет (шаг 23) — на ТОТ ЖЕ день и строго после фронта, и
    // это порядок самого круга: границы сперва двигаются, и только потом хозяин
    // считает, что ему досталось и что он готов отстроить.
    this.queue = insertScheduled(this.queue, {
      day: nextEconomyTickDay(this.day),
      seq: this.nextSeq,
      task: { kind: 'developmentTick' },
    });
    this.nextSeq += 1;

    // Такт соперников (шаг 22) — на ТОТ ЖЕ день и последним: фракции сперва
    // копят, воюют и строят, потом наёмники разбирают то, что из этого вышло.
    // Порядок держит номер постановки, а не совпадение, — поэтому все пять
    // декадных задач и ставятся здесь подряд.
    this.queue = insertScheduled(this.queue, {
      day: nextEconomyTickDay(this.day),
      seq: this.nextSeq,
      task: { kind: 'rivalTick' },
    });
    this.nextSeq += 1;
  }
}
