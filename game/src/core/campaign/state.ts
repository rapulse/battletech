/**
 * День следующего такта экономики: ближайшая граница декады строго после `day`.
 *
 * Выравнивание по декаде — не косметика (см. постановку задачи в конструкторе).
 */
export function nextEconomyTickDay(day: number): number {
  const step = WAR.economy.tickDays;
  return (Math.floor(day / step) + 1) * step;
}

/**
 * Рота в пути (шаг 14).
 *
 * Маршрут лежит в состоянии целиком, а не пересчитывается на каждом шаге:
 * загруженная посреди перелёта кампания обязана долететь ровно туда же и ровно
 * за те же сутки. Деньги за дорогу списаны при постановке — тем же правилом,
 * что и работы стапеля (шаг 13).
 *
 * Перелёт НЕ останавливает очередь суток: ремонт, содержание и лазарет тикают
 * в прыжке и на орбите так же, как на стоянке (решение 11 §7 пайплайна — цех
 * роты стоит на её собственном десантном корабле).
 */
export interface TravelState {
  /** Системы по порядку, включая ту, из которой вышли. */
  readonly path: readonly string[];
  /** Сколько ног маршрута уже пройдено. */
  readonly legIndex: number;
  readonly startDay: number;
  readonly arrivalDay: number;
  /** Уплачено при постановке — для отчёта и замера. */
  readonly cost: number;
}

