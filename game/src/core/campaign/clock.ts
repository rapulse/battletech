/**
 * Время кампании (шаг 10).
 *
 * Два решения, которые дорого менять потом.
 *
 * **1. День — целое число, а не `Date`.** Как только в `core/` появится `Date`,
 * кончится детерминизм: локали, часовые пояса, переход на летнее время и
 * разное поведение движков. Здесь календарь — чистая арифметика, а
 * форматирование строки живёт в слое показа.
 *
 * **2. Отложенные задачи лежат очередью В СОСТОЯНИИ, а не таймерами.** Ремонт
 * заканчивается через три дня, парус заряжается семь, контракт истекает через
 * тридцать, зарплата приходит раз в месяц, фронт сдвигается раз в декаду — всё
 * это одна и та же сущность. Если сделать её здесь правильно, тикер войны
 * (шаг 21) окажется просто ещё одним видом задачи, а не переписыванием слоя
 * времени.
 */

/**
 * Начало отсчёта: 1 января 3053 года — день 0.
 *
 * Эпоха выбрана вместе с каталогом галактики (шаг 14): вторжение кланов
 * остановлено на Тукайиде в мае 3052-го, перемирие заморозило четыре зоны
 * оккупации до 3067 года. Это не украшение даты, а то, что делает статичную
 * карту честной: фронт не двигается, потому что действует перемирие, а не
 * потому что тикер войны ещё не написан (шаг 21 — как раз про то, как оно
 * кончается).
 */
export const EPOCH = { year: 3053, month: 1, day: 1 } as const;

export interface CampaignDate {
  readonly year: number;
  /** 1..12 */
  readonly month: number;
  /** 1..31 */
  readonly day: number;
}

/**
 * Дни от 1970-01-01 по григорианскому календарю (алгоритм Ховарда Хиннанта).
 *
 * Взят готовый выверенный алгоритм, а не написан свой: високосные годы,
 * столетия и четырёхсотлетия — классическое место, где самодельная формула
 * расходится с календарём на один день раз в сто лет и это не находят годами.
 */
function daysFromCivil(year: number, month: number, day: number): number {
  const y = year - (month <= 2 ? 1 : 0);
  const era = Math.floor(y / 400);
  const yoe = y - era * 400;
  const doy = Math.floor((153 * (month + (month > 2 ? -3 : 9)) + 2) / 5) + day - 1;
  const doe = yoe * 365 + Math.floor(yoe / 4) - Math.floor(yoe / 100) + doy;
  return era * 146097 + doe - 719468;
}

function civilFromDays(days: number): CampaignDate {
  const z = days + 719468;
  const era = Math.floor(z / 146097);
  const doe = z - era * 146097;
  const yoe = Math.floor(
    (doe - Math.floor(doe / 1460) + Math.floor(doe / 36524) - Math.floor(doe / 146096)) / 365,
  );
  const y = yoe + era * 400;
  const doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  const mp = Math.floor((5 * doy + 2) / 153);
  const d = doy - Math.floor((153 * mp + 2) / 5) + 1;
  const m = mp + (mp < 10 ? 3 : -9);
  return { year: y + (m <= 2 ? 1 : 0), month: m, day: d };
}

const EPOCH_DAYS = daysFromCivil(EPOCH.year, EPOCH.month, EPOCH.day);

/** Дата по номеру дня кампании. Форматирование строки — не здесь, а в показе. */
export function dateOf(day: number): CampaignDate {
  return civilFromDays(EPOCH_DAYS + day);
}

/** Номер дня кампании по дате. Обратна `dateOf`. */
export function dayOf(date: CampaignDate): number {
  return daysFromCivil(date.year, date.month, date.day) - EPOCH_DAYS;
}

/**
 * Отложенная задача.
 *
 * Размеченное объединение, которое растёт с шагами: `repairJob`/`payroll`/
 * `medbayDone` (шаг 13), `travelLeg`/`surveyDone` (шаг 14),
 * `deliveryArrived` (шаг 15), `contractExpired` (шаг 16), `baysUpgraded`
 * (шаг 19a), `decayTick` (шаг 20), `economyTick` (шаг 21a), `frontTick` (шаг 21b),
 * `rivalTick` (шаг 22).
 */
export type ScheduledTask =
  | { readonly kind: 'debug'; readonly label: string }
  | {
      /** Содержание роты: аренда, зарплаты, обслуживание парка (`company/payroll.ts`). Сама себя переставляет на следующий интервал. */
      readonly kind: 'payroll';
    }
  | {
      /** Пилот в лазарете. Срок посчитан заранее (`company/medbay.ts`) — задача только исполняет исход. */
      readonly kind: 'medbayDone';
      readonly pilotId: string;
    }
  | {
      /**
       * Отдых роты: раз в декаду у каждого пилота в строю заживает одна травма
       * (`company/medbay.ts::restPilot`). Как содержание и затухание, задача
       * сама переставляет себя на следующий круг.
       */
      readonly kind: 'restTick';
    }
  | {
      /**
       * Работа стапеля: ремонт зоны, смена класса, восстановление износа,
       * полевая замена узла (`company/jobs.ts`, `commands/execute.ts`), а с
       * шага 15 — ещё разбор машины и установка узла со склада. `jobId` — то,
       * на что ссылается `CancelJob`; `cost` уже списан при постановке и нужен
       * здесь для честного возврата при отмене.
       *
       * Разбор и установка — работы стапеля, а не отдельная сущность, и это
       * не экономия на типах: они занимают стапель, стоят денег и времени и
       * отменяются той же командой. Разводить их в свой вид задачи значило бы
       * трижды переписать `hasBayFor`, `CancelJob` и проверку `MechHasPendingJob`.
       */
      readonly kind: 'repairJob';
      readonly jobId: string;
      readonly recordId: string;
      readonly work: RepairWork;
      readonly zone?: ZoneId;
      readonly node?: WearNode;
      readonly targetClass?: QualityClass;
      /** Для `installPart` — узел со склада, который встаёт на машину. */
      readonly partId?: string;
      /**
       * Для `refitMech` — целевая сборка и складские записи, которые работа
       * заберёт (шаг 19a).
       *
       * Сборка лежит в задаче ЦЕЛИКОМ, а не пересчитывается по завершении, по
       * той же причине, что и у заказа с доставкой: работа оплачена в день
       * постановки, и из цеха обязана выйти ровно та машина, за которую
       * заплачено, — даже если за это время рота успела продать со склада всё
       * остальное. `partIds` держит железо занятым, пока работа висит в
       * очереди: без него две работы подряд разобрали бы один и тот же ствол
       * дважды.
       */
      readonly assembly?: MechAssembly;
      readonly partIds?: readonly string[];
      /**
       * Для `repaintMech` — раскраска, в которую красят (шаг 50). Нет поля —
       * снять перекраску и вернуть цвета происхождения.
       */
      readonly paint?: string;
      /** Работа на стапеле наземного цеха этого мира (шаг 87), а не корабля. */
      readonly workshop?: string;
      readonly cost: number;
    }
  | {
      /**
       * Нога маршрута дошла до конца: транзит к точке прыжка, прыжок, зарядка
       * паруса (`galaxy/navigation.ts`). Маршрут целиком лежит в состоянии
       * (`CampaignState.travel`), здесь только номер ноги — чтобы задача из
       * старой очереди не могла увести роту по отменённому маршруту.
       */
      readonly kind: 'travelLeg';
      readonly leg: number;
    }
  | {
      /** Разведка системы закончена: точные числа профиля открыты (`galaxy/profile.ts`). */
      readonly kind: 'surveyDone';
      readonly systemId: string;
    }
  | {
      /**
       * Заказанный узел доехал (шаг 15).
       *
       * Узел лежит в задаче целиком, а не пересчитывается по прибытии: заказ
       * оплачен в день оформления, и то, что доедет, обязано быть ровно тем, за
       * что заплачено, — даже если декада на рынке успела смениться, а рота
       * успела улететь на три системы дальше.
       */
      readonly kind: 'deliveryArrived';
      readonly orderId: string;
      readonly part: WarehousePart;
    }
  | {
      /**
       * Срок контракта вышел (шаг 16).
       *
       * Провал по сроку — задача очереди суток, а не проверка при каждом
       * действии: срок обязан сработать сам, даже если рота всё это время
       * чинилась на другом конце Сферы и ни разу не открыла экран контракта.
       * `contractId` сверяется с активным контрактом — задача от разорванного
       * или уже закрытого контракта молча теряется, тем же правилом, что и
       * нога отменённого маршрута.
       */
      readonly kind: 'contractExpired';
      readonly contractId: string;
    }
  | {
      /**
       * Цех расширен: `bays` вырос на ступень (шаг 19a).
       *
       * Задача очереди суток, а не мгновенная кнопка, — тем же правилом, что и
       * любая работа стапеля: цех перестраивается три недели, и всё это время
       * рота живёт на старом числе мест. Стапель при этом НЕ занимается: место
       * не может занимать само себя, а расширение идёт вокруг работающего цеха.
       */
      readonly kind: 'baysUpgraded';
      readonly to: number;
    }
  | {
      /** Ячейка ангара открыта (шаг 75): `hangar` вырос на ступень — та же очередь, что у цеха. */
      readonly kind: 'hangarUpgraded';
      readonly to: number;
    }
  | {
      /**
       * Затухание репутации (шаг 20): отношение тянется к нулю, известность
       * медленнее, надёжность не затухает вовсе.
       *
       * Задача очереди, а не пересчёт при каждом чтении, и это то же решение,
       * что у содержания: затухание обязано идти, пока рота чинится, летит и
       * стоит без работы, — иначе «репутация тускнеет» превратилось бы в
       * «репутация тускнеет, когда на неё смотрят». Сама переставляет себя на
       * следующий месяц.
       */
      readonly kind: 'decayTick';
    }
  | {
      /**
       * Такт экономики фракций (шаг 21a): доход, содержание, отчисление в
       * военный фонд по направлениям.
       *
       * Задача очереди, а не пересчёт при чтении, — то же решение, что у
       * содержания роты и затухания репутации: мир обязан жить, пока рота
       * чинится, летит и стоит без работы. Сама переставляет себя на следующую
       * декаду, и день такта выровнен по ГРАНИЦЕ декады
       * (`state.ts::nextEconomyTickDay`): биржа читает экономику, а состав
       * предложений внутри декады обязан быть неизменным.
       */
      readonly kind: 'economyTick';
    }
  | {
      /**
       * Такт фронта (шаг 21b): наступления по участкам, смена владельцев,
       * клановые набеги, заживление разорения.
       *
       * Четвёртая самопереставляющаяся задача рядом с содержанием, затуханием и
       * тактом экономики. Ставится в очередь ПОСЛЕ `economyTick` и на тот же
       * день: фракции сперва копят, потом воюют накопленным, и порядок держится
       * номером постановки (`ScheduledEvent.seq`), а не совпадением.
       *
       * День выровнен по границе декады той же функцией, что у экономики
       * (`state.ts::nextEconomyTickDay`): биржа читает и владельца, и
       * напряжённость участка, а состав предложений внутри декады обязан быть
       * неизменным.
       */
      readonly kind: 'frontTick';
    }
  | {
      /**
       * Такт развития планет (шаг 23, часть A): стройка на деньги казны и
       * упадок выжженных войной миров.
       *
       * Шестая самопереставляющаяся задача рядом с содержанием, затуханием,
       * экономикой и фронтом. Ставится ПОСЛЕ `frontTick` и на тот же день, и
       * это порядок самого круга: границы сперва двигаются, и только потом
       * хозяин считает, что ему досталось и что он готов отстроить. Держится
       * порядок номером постановки (`ScheduledEvent.seq`), а не совпадением.
       */
      readonly kind: 'developmentTick';
    }
  | {
      /**
       * Такт событий мира (шаг 84): канонические вехи эпохи (`war/events.ts`).
       *
       * Своя самопереставляющаяся задача, ставится ПОСЛЕ `frontTick` и на тот же день: событие
       * читает карту и отношения, какими их оставили дипломатия и бои этой декады, а его договоры,
       * вражда и замыслы ложатся на следующую. Порядок держит номер постановки.
       */
      readonly kind: 'eventTick';
    }
  | {
      /**
       * Такт соперников (шаг 22): их содержание, ремонт, найм, выбор работы и
       * их бои.
       *
       * Пятая самопереставляющаяся задача рядом с содержанием, затуханием,
       * тактом экономики и тактом фронта. Ставится в очередь ПОСЛЕ `frontTick`
       * и на тот же день: фракции сперва копят и воюют, потом наёмники
       * разбирают то, что из этого вышло, — и порядок держится номером
       * постановки (`ScheduledEvent.seq`), а не совпадением.
       *
       * Такт ДЕКАДНЫЙ и выровнен по границе декады той же функцией, что у
       * экономики, фронта и развития (`state.ts::nextEconomyTickDay`). Третьего календаря
       * в игре не заводится: соперник, берущий работу по своему расписанию,
       * разошёлся бы с биржей, которая внутри декады неизменна.
       */
      readonly kind: 'rivalTick';
    };

/**
 * Виды работ стапеля. Расширяется шагами: 13 дал первые четыре, 15 — разбор и
 * установку узла со склада, 19a — переоснащение (мехлаб).
 *
 * Список — источник истины и для типа, и для схемы сохранения (`schema.ts`):
 * два списка одних и тех же имён рано или поздно разошлись бы, и разошлись бы
 * молча.
 */
export const REPAIR_WORKS = [
  'repairZone',
  'upgradeClass',
  'restoreWorn',
  'replacePart',
  'scrapMech',
  'installPart',
  'refitMech',
  'repaintMech',
] as const;

export type RepairWork = (typeof REPAIR_WORKS)[number];

export interface ScheduledEvent {
  readonly day: number;
  /**
   * Номер постановки. Ровно он делает порядок исполнения детерминированным,
   * когда на один день назначено несколько задач: полагаться на порядок
   * вставки в массив или на порядок обхода объекта нельзя (game_core.md §4.7).
   */
  readonly seq: number;
  readonly task: ScheduledTask;
}

/** Порядок исполнения: сначала по дню, при равенстве — по номеру постановки. */
export function compareScheduled(a: ScheduledEvent, b: ScheduledEvent): number {
  return a.day !== b.day ? a.day - b.day : a.seq - b.seq;
}

/** Вставка с сохранением порядка. Очередь всегда отсортирована — сортировать при чтении нечего. */
export function insertScheduled(
  queue: readonly ScheduledEvent[],
  event: ScheduledEvent,
): ScheduledEvent[] {
  const out = [...queue];
  let i = out.length;
  while (i > 0 && compareScheduled(out[i - 1] as ScheduledEvent, event) > 0) i--;
  out.splice(i, 0, event);
  return out;
}

/** Первая задача в очереди, если её день не позже указанного. */
export function nextDue(
  queue: readonly ScheduledEvent[],
  throughDay: number,
): ScheduledEvent | undefined {
  const head = queue[0];
  return head !== undefined && head.day <= throughDay ? head : undefined;
}
