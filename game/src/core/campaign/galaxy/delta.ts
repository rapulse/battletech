import { GALAXY } from './catalog.js';
import type { WorldFocus } from './schema.js';
import type { BuildingKind } from '../war/schema.js';

/**
 * Дельты систем — третий слой галактики (решение 4 §2 `часть2-pipeline.md`).
 *
 * В сохранении лежат **только отличия мира от выводимого**: сменившийся
 * владелец, разорённая промышленность, что игрок разведал, что уже скуплено в
 * лавке. Каталог одинаков у всех кампаний, профиль считается на лету — растёт
 * с игрой только эта разрежённая карта, и растёт она десятками записей, а не
 * тысячами.
 *
 * Запись здесь появляется, когда мир ОТЛИЧАЕТСЯ от канона. Пустая дельта не
 * хранится: `withDelta` выбрасывает её, иначе одно посещение системы означало
 * бы одну строку в сохранении, и разрежённая карта перестала бы быть
 * разрежённой.
 */
export interface SystemDelta {
  /**
   * Владелец сменился: фронт сдвинулся (`war/front.ts`, шаг 21b). Ссылка в
   * реестр акторов.
   *
   * Записи здесь нет, пока мир держит тот же, кто держал его в 3053 году, — в
   * том числе если он его потерял и отбил обратно.
   */
  readonly owner?: string;
  /**
   * Доля разорённой промышленности, 0..1: захват или клановый набег
   * (`war/front.ts`, шаг 21b). Снимает доход фракции, снаряжение гарнизона, его
   * силу в бою и число предложений на бирже; заживает годами.
   */
  readonly ruined?: number;
  /**
   * ВЫЧИЩЕННОСТЬ ОТ ВОЛЬНИЦЫ, 0..1 (шаг 37a): здесь поработал наёмный отряд.
   *
   * Снимает пиратский риск системы, а с ним и пиратскую работу на её бирже.
   * Растёт с каждого выигранного подряда против пиратов — чей угодно, роты или
   * соперника, — и волной задевает соседей за один прыжок.
   *
   * **Свойство МИРА, а не роты, и в этом весь смысл записи.** Вычистить мир мог
   * кто угодно, и след виден всем одинаково — поэтому оно и ложится сюда, рядом
   * с разорением, не ломая чистоту биржи. «Сколько декад рота сидит на планете»
   * — свойство РОТЫ, и о него споткнулся пункт 3 `questions.md`; здесь этой
   * развилки нет.
   *
   * ЗАРАСТАЕТ обратно, как заживает `ruined` (`contracts/pirates.ts`): иначе за
   * длинную кампанию карта вычистилась бы насухо и работа кончилась бы совсем.
   */
  readonly cleared?: number;
  /**
   * Развитие мира — ОТКЛОНЕНИЕ от канонического профиля в целых ступенях
   * (шаг 23, часть A). Плюс — мир отстроен сверх канона, минус — сведён войной
   * ниже него.
   *
   * Здесь, а не в профиле, и это опора решения 4 §2 пайплайна: профиль остаётся
   * чистой функцией от сида, снимок остаётся разрежённым, а мир при этом
   * перестаёт быть вечным. Что одна ступень делает с миром — `galaxy/profile.ts`
   * и `galaxy.json` → `profile.development`; кто и когда её двигает —
   * `war/development.ts`.
   *
   * От `ruined` отличается тем, что НЕ ЗАЖИВАЕТ: разорение — свежий пожар,
   * который проходит за годы, развитие — то, чем мир стал. Выжженный десятью
   * годами войны мир не возвращается к канону сам.
   */
  readonly development?: number;
  /**
   * Фокус мира — ОТКЛОНЕНИЕ от естественного (шаг 25, часть A).
   *
   * Записи нет, пока мир занят тем, чем его занял бы профиль сам
   * (`profile.naturalFocus`), — в том числе если владелец сменил фокус и вернул
   * обратно. Та же дисциплина, что у владельца и развития: ноль дельт даёт
   * осмысленную карту специализаций в первый же день кампании.
   */
  readonly focus?: WorldFocus;
  /**
   * Незавершённая смена фокуса: на что меняют и до какого дня.
   *
   * Два поля, а не одно, и снимаются они вместе. Смена длится игровой год,
   * поэтому её видно в снимке; потеря мира её отменяет — новый хозяин не
   * доводит до конца стройку прежнего.
   */
  readonly focusTo?: WorldFocus;
  readonly focusUntil?: number;
  /**
   * ДАНЬ (шаг 26, часть B): кому мир платит и до какого дня.
   *
   * Владелец при этом НЕ меняется — в том и весь смысл первой ступени
   * подчинения. Победитель облагает мир данью вместо захвата: часть дохода
   * течёт ему, а содержание, гарнизон и администрация остаются на прежнем
   * хозяине. Для сильного это дёшево (захват стоит гарнизона и разорения), для
   * слабого — выживаемо (он не исчезает с карты).
   *
   * Два поля, а не одно, и снимаются они вместе — как незавершённая смена
   * фокуса выше. **Срок конечен, и это главное:** дань истекает и требует
   * подтверждения силой, иначе она стала бы бесплатной вечной рентой, а война —
   * бессмысленной. Смена владельца дань снимает целиком: новый хозяин чужих
   * обязательств не наследует.
   */
  readonly tribute?: string;
  readonly tributeUntil?: number;
  /**
   * Своя доля дани этого мира вместо `diplomacy.tributeShare` (шаг 90): лен платит жалующему Дому меньшую долю
   * (`diplomacy.grantTributeShare`). Живёт только вместе с данью — любая новая запись `tribute` её снимает
   * (`withDelta`), смена владельца — тоже.
   */
  readonly tributeShare?: number;
  /**
   * Столица державы роты (шаг 72a) — мир, куда игрок её перенёс, и ДЕНЬ
   * переноса (шаг 72b: следующий перенос — не раньше чем через полгода).
   *
   * Запись на мире, а не поле состояния: записи нет, пока столица там, где её
   * ставит правило по умолчанию (первый мир роты по каталогу), и старые
   * сохранения читаются без переделки. Запись на мире, которым рота больше не
   * владеет, не действует (`economy.ts::domainCapitalIndex`), а захват её снимает.
   */
  readonly realmCapitalSince?: number;
  /**
   * Метка столицы державы роты (шаг 76). До шага столица без записи была
   * «первым миром роты по каталогу» и переезжала сама на каждый новый мир с
   * меньшим номером. Теперь первый мир роты получает метку сразу, и столицу
   * меняет только перенос; `realmCapitalSince` рядом — день последнего
   * ПЕРЕНОСА, от него считаются 180 суток. Основание державы — не перенос.
   */
  readonly realmCapital?: true;
  /**
   * Рота отказалась от этого мира (шаг 75): до этого дня её полевая армия на
   * него не наступает (`war/front.ts::frontSectors`). Иначе полки, стоящие на
   * театре против нового хозяина, отбивали бы брошенный мир обратно. Снимается
   * любой сменой владельца; истёкшая запись ничего не значит.
   */
  readonly abandonedUntil?: number;
  /**
   * ЛОЯЛЬНОСТЬ МИРА РОТЫ, 0..100 (шаг 85; `war/loyalty.ts`). Есть ровно у миров роты: ставится, когда мир
   * переходит роте (старт по способу получения), снимается, когда уходит. Множит доход и мощность мира;
   * ниже порога мир восстаёт.
   */
  readonly loyalty?: number;
  /**
   * У кого рота получила мир (шаг 85): взяла, купила, приняла в лен или получила по миру. Против его
   * войны падает лояльность, его ополчение поднимает восстание, ему мир отходит. Живёт вместе с `loyalty`.
   */
  readonly formerOwner?: string;
  /** День, когда мир восстал (шаг 85). Снимается подавлением; через `loyalty.revoltDecades` декад мир отходит. */
  readonly revoltSince?: number;
  /**
   * Пираты у дома (шаг 89): до какого дня на бирже мира роты висит оборона против вольницы после прорвавшегося
   * набега. Снимается победой; истёкшее снимает такт развития.
   */
  readonly raidedUntil?: number;
  /**
   * ПОБЕДЫ ДЕРЖАВЫ НАД ВЛАДЕЛЬЦЕМ МИРА (шаг 90): сколько раз рота выиграла здесь работу державы против того, кто
   * миром владеет (`contracts/board.ts::warWorkOffers`). Это и есть право флага на мир врага
   * (`commands/execute.ts::executeConquerWorld`): до шага 90 захват засчитывал любые победы роты на мире — и работу
   * на самого владельца, и держава брала у соседа миры его же контрактами (`notes.md` §10zu п. 4). Смена владельца
   * счёт снимает (`withDelta`): победы над прежним хозяином права на мир нового не дают.
   */
  readonly realmWon?: number;
  /**
   * ПОСТРОЙКИ РОТЫ на мире (шаг 87; `war/buildings.ts`): готовые, в порядке `BUILDING_KINDS`. Действуют, только
   * пока мир роты; на потерянном мире уцелевшие «спят» и снова работают, когда рота его вернёт.
   */
  readonly buildings?: readonly BuildingKind[];
  /** Идущая стройка и набранные ею очки (шаг 87). Снимаются вместе: готовой постройкой, отменой, потерей мира. */
  readonly building?: BuildingKind;
  readonly buildProgress?: number;
  /**
   * ПАМЯТЬ МИРА О РОТЕ (шаг 27a, часть B).
   *
   * Сколько контрактов рота здесь отработала, сколько из них выиграла, за кого
   * дралась в последний раз и в каком году. Записи нет, пока рота на планете не
   * воевала, — и это подавляющее большинство из двух тысяч миров.
   *
   * **Заведено потому, что вопрос был задан неверно.** Выводимость говорит «по
   * умолчанию ВЫВОДИ», а не «не ХРАНИ», а мы превратили её в привычку
   * спрашивать «нельзя ли этого не хранить» вместо «что этот мир должен
   * помнить». Замер снимка на 1095-й день: соперники — 92.8 % файла, дельты
   * систем — 4.4 %. Слой дельт ничем не ограничен, и память о десятках боёв
   * стоит единиц байт на мир.
   *
   * **Что это открывает:** узнаваемость карты. Роту, трижды оборонявшую Сарну,
   * четвёртый контракт там читался ровно так же, как на планете, которую видишь
   * впервые. Мир не помнил ни боёв, ни того, кто их выиграл.
   */
  readonly fought?: number;
  readonly foughtWon?: number;
  readonly foughtFor?: string;
  readonly foughtYear?: number;
  /** Система разведана: точные числа профиля открыты (`Survey`). */
  readonly surveyed?: boolean;
  /** Рота хотя бы раз здесь стояла. */
  readonly visited?: boolean;
  /** Декада, за которую записаны покупки. Ассортимент лавки не хранится — только факт покупки (шаг 15). */
  readonly boughtDecade?: number;
  readonly bought?: readonly string[];
  /**
   * Декада, за которую записаны взятые контракты (шаг 16). Биржа не хранится —
   * только факт взятия, тем же приёмом, что и покупка на рынке. Без этой записи
   * разорванный контракт можно было бы взять заново в той же декаде, и штраф
   * за разрыв перестал бы что-либо значить.
   */
  readonly takenDecade?: number;
  readonly taken?: readonly string[];
}

/**
 * Правка дельты. Отличается от самой дельты ровно одним: поле можно СНЯТЬ,
 * передав `undefined`.
 *
 * Нужно с шага 21b: разорение заживает, и мир, зарубцевавшийся до нуля, обязан
 * уйти из разрежённой карты целиком, а не остаться в ней записью «разорения
 * нет». Иначе разрежённость протекла бы через первую же закончившуюся войну —
 * та же дисциплина, что у `withStanding` и `withFund`.
 */
export type SystemDeltaPatch = { readonly [K in keyof SystemDelta]?: SystemDelta[K] | undefined };

export type GalaxyDeltas = Readonly<Record<string, SystemDelta>>;

export const NO_DELTAS: GalaxyDeltas = Object.freeze({});

export function deltaOf(deltas: GalaxyDeltas, id: string): SystemDelta | undefined {
  return deltas[id];
}

function isEmpty(d: SystemDelta): boolean {
  return Object.values(d).every((v) => v === undefined);
}

/**
 * Дельта с наложенной правкой. Возвращает новую карту — состояние кампании
 * состоит из неизменяемых значений, как и боевое.
 */
export function withDelta(deltas: GalaxyDeltas, id: string, patch: SystemDeltaPatch): GalaxyDeltas {
  const merged: Record<string, unknown> = { ...(deltas[id] ?? {}), ...patch };
  // СМЕНА ВЛАДЕЛЬЦА СНИМАЕТ ДАНЬ (решение пользователя 2026-10-07; замысел — у
  // поля `tribute`): дань — договор владельца с получателем, и новый хозяин чужих
  // обязательств не наследует, каким бы путём мир ни перешёл — захват, покупка,
  // уступка по миру. Здесь, а не у каждого шва: через эту функцию идёт любая
  // запись владельца, и забыть правило новому шву негде. Лен назначает дань уже
  // новому владельцу отдельной правкой, поэтому она держится.
  if ('owner' in patch) {
    const i = GALAXY.require(id);
    const before = deltas[id]?.owner ?? GALAXY.ownerId(i);
    const after = (merged.owner as string | undefined) ?? GALAXY.ownerId(i);
    if (after !== before) {
      if (!('tribute' in patch)) {
        merged.tribute = undefined;
        merged.tributeUntil = undefined;
      }
      // Победы над прежним владельцем (шаг 90) права на мир нового не дают.
      if (!('realmWon' in patch)) merged.realmWon = undefined;
    }
  }
  // Своя доля дани (шаг 90) — свойство именно этой дани: новая запись дани или её снятие долю снимает, если
  // правка не ставит её явно (лен).
  if (('tribute' in patch || merged.tribute === undefined) && !('tributeShare' in patch)) merged.tributeShare = undefined;
  // Снятое поле выбрасывается из записи, а не остаётся в ней ключом со
  // значением `undefined`: снимок обязан быть тем же объектом после круга через
  // JSON, а `JSON.stringify` такие ключи молча теряет.
  for (const k of Object.keys(merged)) if (merged[k] === undefined) delete merged[k];

  const next = { ...deltas };
  if (isEmpty(merged as SystemDelta)) delete next[id];
  else next[id] = merged as SystemDelta;
  return next;
}

/** Текущий владелец системы: дельта, если фронт сдвинулся, иначе канон 3053 года. */
export function ownerOf(deltas: GalaxyDeltas, system: string | number): string {
  const i = typeof system === 'number' ? system : GALAXY.require(system);
  return deltas[GALAXY.id(i)]?.owner ?? GALAXY.ownerId(i);
}

/** Развитие мира в ступенях: дельта, если мир от канона отличается, иначе ноль. */
export function developmentOf(deltas: GalaxyDeltas, id: string): number {
  return deltas[id]?.development ?? 0;
}

/**
 * Фокус мира: дельта, если его кто-то переделал, иначе естественный из профиля.
 *
 * Естественный передаётся аргументом, а не читается здесь: профиль стоит
 * дороже поиска в карте, и звать его ради мира, у которого фокус и так записан,
 * незачем. Тот же приём, что у `developmentOf`, — дельта знает только про
 * отклонение.
 */
export function focusOf(deltas: GalaxyDeltas, id: string, natural: WorldFocus): WorldFocus {
  return deltas[id]?.focus ?? natural;
}

/**
 * Кому мир платит дань на этот день, или `undefined`.
 *
 * Срок проверяется ЗДЕСЬ, а не только тактом снятия: истёкшая запись перестаёт
 * действовать в тот же день, даже если такт до неё ещё не дошёл. Сам такт
 * (`war/diplomacy.ts::diplomacyTick`) запись потом удаляет — ради разрежённости,
 * а не ради правильности.
 */
export function tributeOf(deltas: GalaxyDeltas, id: string, day: number): string | undefined {
  const d = deltas[id];
  if (d?.tribute === undefined) return undefined;
  return (d.tributeUntil ?? 0) > day ? d.tribute : undefined;
}

export function isSurveyed(deltas: GalaxyDeltas, id: string): boolean {
  return deltas[id]?.surveyed === true;
}

export function isVisited(deltas: GalaxyDeltas, id: string): boolean {
  return deltas[id]?.visited === true;
}

/**
 * Что мир помнит о роте (шаг 27a, часть B), или `undefined`, если рота здесь
 * не воевала.
 *
 * Мир БЕЗ записи ничем не отличается от выводимого — в этом вся дисциплина
 * третьего слоя, и здесь она держится тем же приёмом, что у развития и фокуса:
 * отсутствие записи и есть «ничего не было».
 */
export interface WorldMemory {
  /** Сколько контрактов рота здесь отработала. */
  readonly fought: number;
  /** Из них выиграно. */
  readonly won: number;
  /** За кого дралась в последний раз. */
  readonly forWhom: string | undefined;
  /** Год последнего боя. */
  readonly year: number | undefined;
}

export function memoryOf(deltas: GalaxyDeltas, id: string): WorldMemory | undefined {
  const d = deltas[id];
  if (d?.fought === undefined || d.fought <= 0) return undefined;
  return { fought: d.fought, won: d.foughtWon ?? 0, forWhom: d.foughtFor, year: d.foughtYear };
}

/**
 * Записать в память мира отработанный контракт.
 *
 * Зовётся ОДИН РАЗ, из расчёта с нанимателем (`commands/execute.ts`), и только
 * оттуда: второе место, пишущее память, разошлось бы с первым через месяц.
 */
export function withWorldMemory(
  deltas: GalaxyDeltas,
  id: string,
  employer: string,
  won: boolean,
  year: number,
): GalaxyDeltas {
  const was = deltas[id];
  return withDelta(deltas, id, {
    fought: (was?.fought ?? 0) + 1,
    foughtWon: (was?.foughtWon ?? 0) + (won ? 1 : 0),
    foughtFor: employer,
    foughtYear: year,
  });
}
