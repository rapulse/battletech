import { FACTIONS } from '../galaxy/catalog.js';
import type { FactionKind } from '../galaxy/schema.js';

/**
 * Держава игрока как действующее лицо войны (шаг 25, часть C).
 *
 * **Зачем отдельный модуль на две строки.** Владелец системы в дельте — ссылка
 * в реестр акторов, и `makeWarState` молча пропускает незнакомое имя
 * (`if (known === undefined) continue`). Значит, чтобы рота владела планетой, у
 * неё обязано быть имя, которое остальной код узнаёт. Здесь оно одно, и все,
 * кому оно нужно, берут его отсюда, а не пишут строку `'player'` у себя.
 *
 * **Почему это НЕ `warActors(state)` из плана шага 25.** План предлагал функцию
 * «каталог фракций плюс держава игрока» и заменить ею обходы `FACTION_LIST` в
 * `war/`. На шаге 25 такая функция вернула бы `FACTION_LIST` всегда: экономика
 * роты живёт в её кассе (`company.cbills`), а не в `FactionEconomy`, военного
 * фонда и замысла у роты нет, стороной фронта она не является. Заводить
 * абстракцию, у которой сегодня ровно одно поведение, значит писать код, чью
 * правильность нечем проверить. Она понадобится фазе 3, когда у игрока появятся
 * вражда и военный фонд, — тогда и появится, вместе с тем, что ею пользуется.
 *
 * **Вид — `mercenary`, и это не заглушка.** Прецедент стоит в данных: Волчьи
 * Драгуны владеют Аутричем тем же видом и на общих правах с Домами. Отсюда же
 * бесплатно берётся вся политика вокруг мира игрока — `data/galaxy/relations.json`
 * уже говорит, что клан враждует с наёмником на 0.5, пираты на 0.6, а Дом на
 * 0.1. Порог фронта 0.4: мир роты видят кланы и пираты, Дома не трогают.
 */
export const PLAYER_ACTOR_ID = 'player';

/** Вид державы игрока: тот же, что у Волчьих Драгун. */
export const PLAYER_ACTOR_KIND: FactionKind = 'mercenary';

export function isPlayerActor(id: string): boolean {
  return id === PLAYER_ACTOR_ID;
}

/**
 * Вид актора: фракция из каталога или держава игрока.
 *
 * Единственное место, где реестр каталога расширяется игроком. `FACTIONS` —
 * разобранный `factions.json`, статический по построению, и вписывать туда
 * запись на лету значило бы, что каталог зависит от состояния кампании.
 */
export function actorKind(id: string): FactionKind | undefined {
  return isPlayerActor(id) ? PLAYER_ACTOR_KIND : FACTIONS.get(id)?.kind;
}
