import { NamedRngSet } from '../rng/index.js';

/**
 * Потоки бросков кампании (шаг 10).
 *
 * Отдельный набор, а не дополнение к боевым `STREAMS`, и это не вкусовщина.
 * Снимок набора перечисляет все его потоки, а боевой снимок входит в
 * `serializeBattleState`; допиши сюда хоть одно имя в `STREAMS` — и
 * закреплённый golden-хэш боя разойдётся, хотя правила боя не менялись.
 *
 * Префикс `camp.` тоже не украшение: имя `campaign` в боевом наборе уже занято
 * (`sim/scenario.ts` генерирует им пилотов). Одноимённые потоки боя и кампании
 * тянули бы числа из одной последовательности, и реплей поехал бы незаметно —
 * ровно тот класс поломки, ради которого потоки вообще именованные.
 *
 * Потоки заведены с запасом, под шаги 11–16: пустой поток ничего не стоит, а
 * добавленный позже сдвинул бы… нет, не сдвинул бы — сид выводится из имени.
 * Но заводить их разом всё равно правильнее: список читается как карта того,
 * что в кампании вообще бросает кубик.
 */
export const CAMPAIGN_STREAMS = [
  /** Порождение мира: свойства систем, население, промышленность (шаг 14). */
  'camp.world',
  /** Ассортимент и цены лавок (шаг 15). */
  'camp.market',
  /** Порождение контрактов и составов противника (шаг 16). */
  'camp.contracts',
  /** Что уцелело с поля: трофеи и целые узлы (шаг 12). */
  'camp.salvage',
  /** Износ и деградация узлов (шаг 11). */
  'camp.wear',
  /** Прочее: происшествия, найм, слухи. */
  'camp.events',
  /**
   * Тикер войны: какой участок фронта разыгрывается и удалось ли наступление
   * (шаг 21b).
   *
   * Свой поток, а не `camp.events`, и это то же решение, что развело броски
   * биржи и броски состава противника: мир обязан жить одинаково независимо от
   * того, сколько раз игрок открыл экран и сколько происшествий с ним случилось
   * по дороге. Общий поток означал бы, что фронт сдвинулся иначе, потому что
   * рота наняла пилота.
   */
  'camp.war',
  /**
   * Соперники: их ремонт, найм, выбор работы и их бои (шаг 22).
   *
   * Свой поток по той же причине, по которой шаг 21b развёл броски фронта и
   * броски происшествий: мир обязан жить одинаково независимо от того, что
   * делает рота. Общий поток означал бы, что соперник взял другой контракт,
   * потому что игрок нанял пилота, — и наоборот, что износ машины игрока
   * зависит от того, сколько боёв отыграли соперники.
   */
  'camp.rivals',
] as const;

export type CampaignStreamName = (typeof CAMPAIGN_STREAMS)[number];

export type CampaignRngState = Readonly<Record<CampaignStreamName, number>>;

/** Набор потоков одной кампании. Входит в снимок состояния и в его хэш. */
export class CampaignRngSet extends NamedRngSet<CampaignStreamName> {
  constructor(masterSeed: number) {
    super(masterSeed, CAMPAIGN_STREAMS);
  }
}
