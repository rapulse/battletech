import { PILOTS } from '../../data/index.js';
import type { Pilot } from '../../model/Pilot.js';
import type { Rng } from '../../rng/index.js';
import { CLAN_IDS, HOUSE_IDS } from '../../rules/names.js';
import { makePilot } from '../../rules/skills.js';

/**
 * Кто пришёл на объявление о найме (переработка найма 2026-09-10).
 *
 * До этой правки найм был покупкой: игрок называл тир, платил по прейскуранту и
 * получал ровно то, что заказал. Кандидата не существовало как события — был
 * ползунок качества с ценником, и «нанять ветерана» отличалось от «нанять
 * новобранца» только суммой в кассе.
 *
 * Стало: **попытка вместо покупки**. Раз в две недели рота может дать
 * объявление (`economy.json → hiring`), и кто на него придёт — бросок. Чем выше
 * выучка, тем реже (веса убывают), а выше сферного потолка не приходит НИКТО,
 * кроме клановых воинов, которых видно раз в двадцать попыток.
 *
 * Полосы не пересекаются намеренно: пока они перекрывались бы, «клановец» был
 * бы просто редкой строкой в той же таблице, а не другим человеком. Сейчас
 * любой клановый воин сильнее любого сферного наёмника — и это ровно то, чем
 * кланы были в каноне для Внутренней Сферы 3050-х.
 */

/** Ступень выучки по весам полосы: чем выше, тем реже. */
function pickTier(rng: Rng, band: { minTier: number; maxTier: number; weights: readonly number[] }): number {
  const total = band.weights.reduce((sum, w) => sum + w, 0);
  let roll = rng.next() * total;
  for (let i = 0; i < band.weights.length; i++) {
    roll -= band.weights[i] ?? 0;
    if (roll < 0) return band.minTier + i;
  }
  return band.maxTier;
}

/**
 * Вытянуть кандидата.
 *
 * `id` задаёт вызывающий: у роты свои номера пилотов, и придумывать их здесь
 * значило бы знать про ростер. Порядок бросков — сторона, ступень, сам пилот —
 * зафиксирован; новый бросок дописывается в конец.
 */
export function rollRecruit(rng: Rng, id: string, fameBonus = 0): Pilot {
  const r = PILOTS.recruits;
  const clan = rng.next() < r.clanChance;
  const band = clan ? r.clan : r.sphere;
  // ИЗВЕСТНОСТЬ ПОДНИМАЕТ СТУПЕНЬ, НО НЕ ЛОМАЕТ ПОЛОСУ (шаг 20 + правка
  // 2026-09-10). К громкому отряду идут пилоты лучше — в казармах стоит
  // очередь. Но выше сферного потолка слава не поднимает никого: клановый воин
  // приходит по своему броску, а не за репутацию.
  const tier = Math.min(band.maxTier, pickTier(rng, band) + Math.max(0, Math.round(fameBonus)));
  const affiliation = clan ? rng.pick(CLAN_IDS) : rng.pick(HOUSE_IDS);

  return makePilot(rng, {
    id,
    affiliation,
    tier,
    minLevel: band.minTier,
    maxLevel: band.maxTier,
    // ПОТОЛОК ТАЛАНТА — СВОЙ У ПОЛОСЫ (правка 2026-09-10, решение
    // пользователя). У Сферы он широкий: наёмник бывает и бесперспективным, и
    // самородком. У клана узкий и высокий — 9-10 по каждой строке: клановому
    // воину полагается расти. До правки он приходил с уровнем 8-10 при общем
    // потолке 4-10, и потолок почти всегда оказывался равен уровню — в среднем
    // клановцу оставалось четверть ступени роста на всю кампанию, то есть он
    // приходил законченным.
    capMin: band.capMin,
    capMax: band.capMax,
  });
}
