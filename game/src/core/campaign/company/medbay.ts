import { ECONOMY } from '../../data/index.js';
import type { Pilot } from '../../model/Pilot.js';

/**
 * Лазарет (шаг 13): раненый пилот возвращается в строй не мгновенно, а через
 * очередь суток (`clock.ts`), как и любая другая работа кампании.
 *
 * Написано и покрыто тестами здесь; вызывающая сторона (запись `out`-статуса
 * пилота в лазарет по итогам боя) появляется в шаге 16 вместе с
 * `ResolveContract` — тем же порядком, что и `awardXp`/`trainSkill` в шаге 11,
 * подключённые только шагом 12 (опора §1 «Чего нет вовсе»).
 */

/** Срок лечения: растёт с числом травм, но не бывает короче минимума. */
export function treatmentDays(injuries: number): number {
  return Math.max(ECONOMY.medbay.minimumDays, injuries * ECONOMY.medbay.daysPerInjury);
}

/** Пилот, поставленный в лазарет: статус уже `out`, срок лечения посчитан. */
export function admitToMedbay(pilot: Pilot): { readonly pilot: Pilot; readonly days: number } {
  return { pilot: pilot.status === 'out' ? pilot : { ...pilot, status: 'out' }, days: treatmentDays(pilot.injuries) };
}

/** Выписка: травмы сброшены, пилот снова годен к вылету. */
export function dischargeFromMedbay(pilot: Pilot): Pilot {
  return { ...pilot, status: 'active', injuries: 0 };
}

