/**
 * ТРАВМЫ ЗАЖИВАЮТ САМИ (правка 2026-09-08).
 *
 * **Что было не так.** Счётчик травм рос только в одну сторону. В лазарет
 * пилота отправлял ПОРОГ (`injury.outAt`), и только оттуда он выходил с нулём;
 * пилот с одной-пятью травмами оставался в строю и таскал их до конца
 * кампании — с постоянным −1 к Стрельбе и Пилотированию за каждые две, худшим
 * катапультированием и лишними срывами проверок. Вылечиться можно было, только
 * ПОСТРАДАВ СИЛЬНЕЕ, — и ветеран, переживший десяток боёв, оказывался хуже
 * новичка, которого только что наняли.
 *
 * **Как теперь.** Раз в декаду каждый пилот в строю теряет одну травму. Тяжесть
 * при этом сохраняется: пять травм заживают полсотни суток, а вылет с ними
 * никто не запрещает — просто это выбор игрока, а не приговор. Кто нужен целым
 * раньше, отправляется в лазарет командой (`treatPilot`) и платит тем же, чем
 * платят все работы кампании, — временем.
 *
 * Потерянного не касается: `lost` необратим. Лежащего в лазарете — тоже: у него
 * свой срок и своя выписка, и вычитать травмы дважды значило бы сократить срок
 * лечения задним числом.
 */
export function restPilot(pilot: Pilot): Pilot {
  if (pilot.status !== 'active' || pilot.injuries <= 0) return pilot;
  return { ...pilot, injuries: pilot.injuries - 1 };
}
