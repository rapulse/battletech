import type { Company } from '../company/types.js';
import type { ReputationState } from '../reputation/state.js';

/**
 * Отряд-соперник (шаг 22, M11-C).
 *
 * **Соперник — это `Company` и ничего сверх неё.** Машины, пилоты, склад,
 * деньги, стапели, разорение — те же поля, те же функции (`payroll`,
 * `chargeUnavoidable`, `repairPlan`, `debrief`), тот же основатель
 * (`company/founding.ts`). Как только у проекта появится «правило для
 * соперников», у экономики станет два набора правил, и разойдутся они молча —
 * ловушка 1 плана шага 22.
 *
 * Всё, что здесь дописано поверх роты, — это то, чего у роты игрока нет НЕ
 * потому, что она другая, а потому, что это лежит у неё в `CampaignState`
 * рядом: место (`systemId`), репутация и имя.
 *
 * **Соперники лежат в состоянии, а не выводятся** (решение 1 шага 22). У
 * соперника есть ИСТОРИЯ — парк, потери, отношения у нанимателей, место в
 * таблице, — и вывести её из сида нельзя ровно по той же причине, по которой не
 * выводится репутация игрока (`reputation/state.ts`): журнал не хранится, а
 * пересчёт сделал бы загруженную кампанию другой.
 */
export interface Rival {
  /** `R1`…`Rn`. Он же префикс id машин и пилотов отряда. */
  readonly id: string;
  readonly name: string;
  /**
   * Отряд реестра MRBC, чьё имя и герб носит соперник (`data/rivals.json` →
   * `registry`). У откомандирования великого полка это id самого полка: «3-я
   * рота «Гончих Келла»» ходит под гербом Гончих, и это не подмена, а лор.
   */
  readonly unitId: string;
  /**
   * Номер герба в наборе НАЁМНИКОВ (`ui/mercenaries.jpg`), не в наборе игрока.
   *
   * Лежит здесь, а не в `Company.emblem`, потому что это разные атласы: у роты
   * игрока герб из `ui/company.jpg`, и одно поле на два набора означало бы, что
   * один и тот же номер показывает разные картинки в зависимости от того, чей
   * это отряд. Герб привязан к ИМЕНИ: разъедься они — Гончие Келла вышли бы под
   * черепом Рейнджеров Уако.
   */
  readonly emblem: number;
  /** Ступень из `data/rivals.json` → `tiers`: чем отряд был, когда его основали. */
  readonly tier: string;
  /**
   * Значится ли отряд в реестре MRBC — то есть носит ли он каноническое имя и
   * герб. Безымянные вольные отряды не значатся: их в Сфере тысячи, и в реестр
   * попадает верхушка. Они существуют, воюют и разоряются наравне со всеми, но
   * в таблице видны, только когда стоят с ротой в одной системе.
   */
  readonly registered: boolean;
  readonly company: Company;
  /** Где отряд стоит. Соперник летает тем же способом, что рота, — от системы к соседней. */
  readonly systemId: string;
  /**
   * Репутация отряда у фракций.
   *
   * Та же структура, что у игрока, и это не роскошь: `missionAllowed`
   * спрашивается с ЕГО отношением и ЕГО известностью (ловушка 2 части B), иначе
   * соперник-новичок брался бы за штурмы, которых ему никто не предложит.
   *
   * Матрица отношений ФРАКЦИЙ здесь всегда пустая: она свойство МИРА, а не
   * отряда, и живёт в одном экземпляре — в `CampaignState.reputation`. Там, где
   * она нужна (расход прибавки по политической сети), её подставляет
   * `withWorldRelations`.
   */
  readonly reputation: ReputationState;
  /** Сколько работы отряд взял и сколько довёл до конца — для сводки и для таблицы. */
  readonly contracts: number;
  readonly wins: number;
  /**
   * Рейтинг на конец предыдущего такта.
   *
   * Хранится, потому что «движение в таблице» иначе неоткуда взять: рейтинг
   * СЧИТАЕТСЯ (`contracts/threat.ts::companyRating`), а вот каким он был декаду
   * назад — это уже история, и она не выводится.
   */
  readonly ratingBefore: number;
}

/**
 * Рейтинговая таблица целиком: соперники и то, что нужно строке игрока.
 *
 * Контейнер, а не голый массив, ровно из-за `playerRatingBefore`: движение роты
 * игрока в таблице — такая же история, как движение соперника, и хранить её
 * больше негде. В `Company` ей не место — это свойство ТАБЛИЦЫ, а не отряда.
 */
/**
 * Великий полк реестра MRBC (шаг 22c) — действующее лицо, а не строка таблицы.
 *
 * **Хранится АГРЕГАТОМ, и это вынужденно, а не небрежно.** У Волчьих Драгун
 * пятьсот сорок машин; семь полков списком записей весили бы в снимке больше,
 * чем вся остальная кампания вместе взятая (замер: триста ротных отрядов дают
 * 2.9 МБ, семь полков дали бы вдесятеро). Поэтому полк хранит СОСТАВ — сколько
 * машин, какого класса, какого веса, с какой выучкой, — а в бой выходит
 * настоящими машинами, которые собирает тот же `contracts/opfor.ts::buildForce`,
 * что и гарнизон мира и противника на контракт игрока.
 *
 * Это та же граница точности, на которой стоит фронт: армии фракций тоже
 * существуют весами и материализуются в машины на бой. Не вторые правила —
 * другой уровень записи.
 */
export interface Regiment {
  readonly id: string;
  readonly name: string;
  readonly emblem: number;
  readonly cert: string;
  readonly base: string;
  readonly holdsWorld: boolean;
  /** Канонический состав: к нему полк отстраивается, его же он не превышает. */
  readonly fullMechs: number;
  /** Машин СЕЙЧАС. Падает от потерь, растёт восстановлением, ниже `minShare` не уходит. */
  readonly mechs: number;
  /**
   * Касса полка (шаг 22c, аудит фонового цикла).
   *
   * Первая версия дала полку потери и не дала гонорара — петля не замыкалась, и
   * за триста дней Драгуны сточились с 540 машин до 83. Теперь наниматель платит
   * из военного фонда, а полк на эти деньги чинит и докупает машины: круг
   * «повоевал → получил → восстановился» у него тот же, что у роты игрока.
   */
  readonly cbills: number;
  readonly quality: 'recovered' | 'standard' | 'military' | 'master';
  readonly tons: number;
  readonly skill: number;
  /** Где полк работает сейчас. Из этого читается, с кем он воюет. */
  readonly systemId: string;
  /**
   * Чей был мир, когда полк на него встал (шаг 82). Сменился владелец — мир захвачен, и полк
   * уходит, а не нанимается к захватчику (решение пользователя 2026-09-30).
   */
  readonly employer: string;
  readonly contracts: number;
  readonly wins: number;
  readonly ratingBefore: number;
  /**
   * Наём державой роты (шаг 89, `hire.ts`): против кого и до какого дня. Пока поле есть, наниматель полка —
   * держава (`employer`), подряды — только против `against`, без гонорара и без перелёта. Нет поля — полк
   * живёт по правилам шага 82.
   */
  readonly hire?: RegimentHire;
}

export interface RegimentHire {
  readonly against: string;
  readonly until: number;
}

export interface RivalsState {
  readonly list: readonly Rival[];
  /** Великие полки: те же лица, только записанные составом (см. `Regiment`). */
  readonly regiments: readonly Regiment[];
  readonly playerRatingBefore: number;
  /** Сколько отрядов уже разорилось за кампанию: в таблицу они не попадают, в сводку — да. */
  readonly bankrupt: number;
  /** Сколько сформировалось новых: рынок наёмников не пустеет (`formationPerTick`). */
  readonly formed: number;
  /** Следующий свободный номер отряда: id не переиспользуются даже после разорения. */
  readonly nextId: number;
}

export const NO_RIVALS: RivalsState = Object.freeze({
  list: [],
  regiments: [],
  playerRatingBefore: 0,
  bankrupt: 0,
  formed: 0,
  nextId: 1,
});

/**
 * Репутация соперника, дополненная политической картой МИРА.
 *
 * Матрица отношений фракций одна на кампанию: её двигает такт фронта
 * (`war/front.ts`), и вторая её копия у каждого соперника разъехалась бы с
 * первой на первом же наступлении. Поэтому соперник хранит только свои три оси,
 * а карту ему подставляют здесь — на входе в те функции, которым она нужна
 * (`reputation/accrual.ts::contractReputation`).
 */
export function withWorldRelations(rep: ReputationState, world: ReputationState): ReputationState {
  return { ...rep, relations: world.relations };
}

export function findRival(rivals: RivalsState, id: string): Rival | undefined {
  return rivals.list.find((r) => r.id === id);
}

/** Соперник с наложенной правкой. Список неизменяем — как и всё внутри `CampaignState`. */
export function withRival(rivals: RivalsState, rival: Rival): RivalsState {
  return { ...rivals, list: rivals.list.map((r) => (r.id === rival.id ? rival : r)) };
}
