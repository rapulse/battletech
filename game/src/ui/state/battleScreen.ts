import { battle } from './battle.svelte.js';
import { campaign } from './campaign.svelte.js';

/**
 * ЕДИНСТВЕННЫЙ вход на экран боя из кампании.
 *
 * Экран боя показывает то, что лежит в сторе боя, а стор боя живёт только в
 * памяти вкладки: в сохранение он не пишется и после перезагрузки страницы
 * поднимается песочницей из конструктора — учебной стычкой «звено на звено».
 * Кампания при этом помнит, что звено выведено (`ActiveContract.sortie` лежит
 * в сохранении), и честно рисует кнопку «в бой». Раз стор и сохранение
 * расходятся, ставить `screen = 'battle'` голым присваиванием нельзя: игрок
 * попадал в чужой бой, где нет ни его машин, ни исхода — панель исхода
 * рисуется только в режиме контракта, — и победа в нём ничего не закрывала.
 *
 * Поэтому вход один и он сначала СВЕРЯЕТ бой с вылетом. Не сошлось — бой
 * пересобирается по брифингу: те же сиды, та же карта, тот же противник. Ходы,
 * отыгранные до закрытия окна, при этом теряются — состояние боя в сохранение
 * не пишется (см. `notes.md`), — но игрок возвращается в свой бой, а не в
 * чужой.
 */
export function enterBattleScreen(): void {
  if (campaign.hasDebrief) {
    campaign.screen = 'debrief';
    return;
  }
  const brief = campaign.sortieBrief;
  if (brief !== null && !battle.matchesContract(brief)) battle.startFromBrief(brief);
  campaign.screen = 'battle';
}
